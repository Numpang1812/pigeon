/** Even-odd point-in-ring test on (x = lng, y = lat). */
function point_in_ring(lat: number, lng: number, ring: Ring): boolean {
	let inside = false;
	for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
		const [xi, yi] = ring[i];
		const [xj, yj] = ring[j];
		const intersects =
			yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
		if (intersects) inside = !inside;
	}
	return inside;
}

const cache = new Map<string, boolean>();
const CACHE_LIMIT = 60000;

/**
 * True when the point falls on land. Half-degree memoised: event generation
 * hits the same anchor cells repeatedly across viewport and route queries.
 */
export function is_land(lat: number, lng: number): boolean {
	if (lat <= -70) return true; // Antarctic cap
	if (lat >= 84 || lat < -70) return false;

	const key = `${Math.round(lat * 2)},${Math.round(lng * 2)}`;
	const hit = cache.get(key);
	if (hit !== undefined) return hit;

	let land = false;
	for (const ring of RINGS) {
		if (point_in_ring(lat, lng, ring)) {
			land = true;
			break;
		}
	}

	if (cache.size > CACHE_LIMIT) cache.clear();
	cache.set(key, land);
	return land;
}
